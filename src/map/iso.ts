let map: Map<number, string> | null = null

/** ISO alpha-3 code for a numeric id (number or zero-padded string), if known. */
export function isoA3FromNumeric(id: string | number | undefined): string | undefined {
  if (id === undefined || id === null) return undefined
  const n = typeof id === 'number' ? id : /^\d+$/.test(id) ? Number(id) : NaN
  if (!Number.isFinite(n)) return undefined
  if (!map) {
    map = new Map()
    for (let i = 0; i + 6 <= TABLE.length; i += 6) map.set(Number(TABLE.slice(i, i + 3)), TABLE.slice(i + 3, i + 6))
  }
  return map.get(n)
}
